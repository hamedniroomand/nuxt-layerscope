import { LayerscopeError } from '#src/errors.ts';
import { plural } from '#src/utils/strings.ts';

import { DEFAULT_BUILD_DIR } from './build-dir.ts';
import type { OldConfig } from './old-config.ts';
import type { AllowedEdge } from './types.ts';

/** Escapes the line terminators too, which cannot stand inside a string literal. */
export function quote(text: string): string {
  const escaped = text
    .replaceAll('\\', '\\\\')
    .replaceAll("'", String.raw`\'`)
    .replaceAll('\n', String.raw`\n`)
    .replaceAll('\r', String.raw`\r`)
    .replaceAll('\u2028', String.raw`\u2028`)
    .replaceAll('\u2029', String.raw`\u2029`);
  return `'${escaped}'`;
}

/** A line terminator would end a `//` comment, and the rest of the line would be code. */
function oneLine(text: string): string {
  return text.replaceAll(/[\n\r\u2028\u2029]/gu, ' ');
}

function property(name: string): string {
  return /^[A-Za-z_$][\w$]*$/u.test(name) ? name : quote(name);
}

function layerLines(layer: string, edges: AllowedEdge[]): string[] {
  if (edges.length === 0) {
    return [`    ${property(layer)}: { allow: [] },`];
  }
  return [
    `    ${property(layer)}: {`,
    '      allow: [',
    ...edges.map(
      edge =>
        `        ${quote(edge.to)}, // ${plural(edge.count, 'reference')}, e.g. ${oneLine(edge.example)}`,
    ),
    '      ],',
    '    },',
  ];
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const prototype: unknown = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

/**
 * Writes a value of a loaded config as source code. A config holds only plain data, so a value of
 * another type (a function, a RegExp, a Date) stops `init`: to skip it would lose the key.
 */
export function renderValue(value: unknown, path: string, file: string, indent = ''): string {
  if (typeof value === 'string') {
    return quote(value);
  }
  if (typeof value === 'number' || typeof value === 'boolean' || value === null) {
    return String(value);
  }
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    const items = value.map(
      (item: unknown, index) => `${inner}${renderValue(item, `${path}[${index}]`, file, inner)},`,
    );
    return items.length === 0 ? '[]' : ['[', ...items, `${indent}]`].join('\n');
  }
  if (isPlainObject(value)) {
    const entries = Object.entries(value)
      .filter(([, item]) => item !== undefined)
      .map(
        ([key, item]) =>
          `${inner}${property(key)}: ${renderValue(item, `${path}.${key}`, file, inner)},`,
      );
    return entries.length === 0 ? '{}' : ['{', ...entries, `${indent}}`].join('\n');
  }
  throw new LayerscopeError(
    `Cannot keep the key ${path} of ${file}: its value is not plain data, for example a function or a RegExp. Remove the key from that file and run init again, or write the new config by hand.`,
  );
}

/** The keys of the old config that `init` does not write itself, in their order. */
function keptLines(kept: OldConfig | undefined): string[] {
  if (kept === undefined) {
    return [];
  }
  return Object.entries(kept.config)
    .filter(([key, value]) => key !== 'layers' && key !== 'buildDir' && value !== undefined)
    .map(([key, value]) => `  ${property(key)}: ${renderValue(value, key, kept.file, '  ')},`);
}

/**
 * `buildDir` is written only when it is not `.nuxt`, so `check` reads the same directory. `kept` is
 * the old config: its keys other than `layers` and `buildDir` come first, with the same values.
 */
export function renderConfig(
  layers: string[],
  edges: AllowedEdge[],
  buildDir = DEFAULT_BUILD_DIR,
  kept?: OldConfig,
): string {
  return [
    "import { defineConfig } from 'nuxt-layerscope';",
    '',
    '// Generated by `layerscope init`. Delete a line to forbid that dependency.',
    'export default defineConfig({',
    ...keptLines(kept),
    ...(buildDir === DEFAULT_BUILD_DIR ? [] : [`  buildDir: ${quote(buildDir)},`]),
    '  layers: {',
    ...layers.flatMap(layer =>
      layerLines(
        layer,
        edges.filter(edge => edge.from === layer),
      ),
    ),
    '  },',
    '});',
    '',
  ].join('\n');
}
